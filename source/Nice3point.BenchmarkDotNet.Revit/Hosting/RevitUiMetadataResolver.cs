using System.Reflection;
using System.Reflection.PortableExecutable;
#if NET
using System.Runtime.Loader;
#endif

namespace Nice3point.BenchmarkDotNet.Revit.Hosting;

/// <summary>
///     Resolves RevitAPIUI in the BenchmarkDotNet host process to the metadata of the installed assembly.
/// </summary>
/// <remarks>
///     RevitAPIUI.dll depends on native libraries that load only inside Revit.exe.
///     The host process reads the metadata of every benchmark type and of every referenced assembly.
///     The resolver loads a copy of the installed assembly marked as IL-only, without native entry points and directories.
///     The host process never calls a member of the copy.
///     The benchmark processes resolve RevitAPIUI unchanged.
/// </remarks>
internal static class RevitUiMetadataResolver
{
    private const string AssemblyName = "RevitAPIUI";
    private const string GeneratedProgramTypeName = "BenchmarkDotNet.Autogenerated.UniqueProgramName";

    // IMAGE_COR20_HEADER offsets.
    private const int CorFlagsOffset = 16;
    private const int CorEntryPointOffset = 20;
    private const int CorVTableFixupsOffset = 48;
    private const byte IlOnlyFlag = 0x1;

    // IMAGE_OPTIONAL_HEADER64 offsets.
    private const int EntryPointOffset = 16;
    private const int DataDirectoriesOffset = 112;
    private const int DataDirectorySize = 8;

    // IMAGE_DIRECTORY_ENTRY indexes of the native data directories:
    // 0 - export table
    // 1 - import table
    // 2 - resource table
    // 3 - exception table
    // 5 - base relocation table
    // 6 - debug data
    // 9 - thread local storage table
    // 10 - load configuration table
    // 11 - bound import table
    // 12 - import address table
    // 13 - delay import descriptor
    private static readonly int[] NativeDirectories = [0, 1, 2, 3, 5, 6, 9, 10, 11, 12, 13];

    private static readonly Lazy<Assembly?> Image = new(LoadImage);

    /// <summary>
    ///     Registers the resolver in the BenchmarkDotNet host process.
    /// </summary>
    /// <remarks>
    ///     The call has no effect in a benchmark process and inside Revit.
    ///     On .NET Framework, the resolver precedes the Revit assembly resolver of the injector.
    /// </remarks>
    public static void Register()
    {
        if (Assembly.GetEntryAssembly() is not { } entryAssembly || entryAssembly.GetType(GeneratedProgramTypeName) is not null)
        {
            return;
        }

#if NET
        AssemblyLoadContext.Default.Resolving += OnResolving;
#else
        AppDomain.CurrentDomain.AssemblyResolve += OnAssemblyResolve;
#endif
    }

#if NET
    private static Assembly? OnResolving(AssemblyLoadContext context, AssemblyName assemblyName)
    {
        return assemblyName.Name == AssemblyName ? Image.Value : null;
    }
#else
    private static Assembly? OnAssemblyResolve(object? sender, ResolveEventArgs args)
    {
        return new AssemblyName(args.Name).Name == AssemblyName ? Image.Value : null;
    }
#endif

    private static Assembly? LoadImage()
    {
        // RevitAPIUI.dll lies next to RevitAPI.dll of the Revit installation the injector selects.
        var installationPath = Path.GetDirectoryName(typeof(Element).Assembly.Location)!;
        var assemblyPath = Path.Combine(installationPath, $"{AssemblyName}.dll");
        if (!File.Exists(assemblyPath))
        {
            return null;
        }

        var image = File.ReadAllBytes(assemblyPath);
        if (!TryRemoveNativeCode(image))
        {
            return null;
        }

#if NET
        return AssemblyLoadContext.Default.LoadFromStream(new MemoryStream(image));
#else
        return Assembly.Load(image);
#endif
    }

    private static bool TryRemoveNativeCode(byte[] image)
    {
        PEHeaders headers;
        using (var stream = new MemoryStream(image))
        {
            headers = new PEHeaders(stream);
        }

        if (headers.PEHeader?.Magic != PEMagic.PE32Plus || headers.CorHeader is null)
        {
            return false;
        }

        var corHeaderOffset = headers.CorHeaderStartOffset;
        Array.Clear(image, corHeaderOffset + CorFlagsOffset, 4);
        image[corHeaderOffset + CorFlagsOffset] = IlOnlyFlag;
        Array.Clear(image, corHeaderOffset + CorEntryPointOffset, 4);
        Array.Clear(image, corHeaderOffset + CorVTableFixupsOffset, DataDirectorySize);

        var peHeaderOffset = headers.PEHeaderStartOffset;
        Array.Clear(image, peHeaderOffset + EntryPointOffset, 4);
        foreach (var directory in NativeDirectories)
        {
            Array.Clear(image, peHeaderOffset + DataDirectoriesOffset + directory * DataDirectorySize, DataDirectorySize);
        }

        return true;
    }
}
