using System.Reflection;

namespace Nice3point.BenchmarkDotNet.Revit.Hosting;

/// <summary>
///     Provides the facts about the BenchmarkDotNet host process.
/// </summary>
internal static class BenchmarkHostProcess
{
    private const string GeneratedProgramTypeName = "BenchmarkDotNet.Autogenerated.UniqueProgramName";

    /// <summary>
    ///     Gets a value indicating whether the current process is the BenchmarkDotNet host process.
    /// </summary>
    /// <value>
    ///     <see langword="false" /> in a benchmark process that runs a generated program, and inside Revit.
    /// </value>
    public static bool IsCurrent { get; } = Assembly.GetEntryAssembly() is { } entryAssembly && entryAssembly.GetType(GeneratedProgramTypeName) is null;
}
