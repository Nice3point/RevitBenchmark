using System.Globalization;
using System.Reflection;
using BenchmarkDotNet.Engines;
using Nice3point.BenchmarkDotNet.Revit.Ui.Messages;
using Nice3point.Revit.Injector.Ui;
#if NET
using System.Runtime.Loader;
#else
using System.Diagnostics;
#endif

namespace Nice3point.BenchmarkDotNet.Revit.Ui;

/// <summary>
///     Represents the entry point that runs generated benchmark programs inside the Revit user interface application.
/// </summary>
/// <remarks>
///     The runner sends <see cref="RevitUiBenchmarkReady" /> once Revit starts.
///     Every <see cref="RevitUiBenchmarkExecution" /> runs one benchmark.
///     <see cref="RevitUiBenchmarkCompletion" /> reports the end of the benchmark.
///     A benchmark runs synchronously on the Revit thread inside a Revit API context.
///     The runner finishes once the host process closes the connection.
/// </remarks>
[UsedImplicitly]
internal sealed class RevitUiBenchmarkRunner : IRevitUiEntryPoint
{
    private const string RunnableTypeName = "BenchmarkDotNet.Autogenerated.Runnable_{0}";
    private const string RunMethodName = "Run";

    /// <summary>
    ///     Gets the context of the Revit user interface application.
    /// </summary>
    /// <value>Defaults to <see langword="null" /> outside the Revit user interface application.</value>
    public static RevitUiContext? Context { get; private set; }

    /// <inheritdoc />
    public async Task RunAsync(RevitUiContext context)
    {
        Context = context;
        context.Send(new RevitUiBenchmarkReady { ProcessId = GetProcessId() }.Serialize());

        while (await context.ReceiveAsync().ConfigureAwait(false) is { } message)
        {
            if (RevitUiBenchmarkCommand.Parse(message) is not RevitUiBenchmarkExecution execution)
            {
                continue;
            }

            var exitCode = -1;
            await context.InvokeAsync(() =>
            {
                exitCode = RunBenchmark(context, execution);
                return default;
            }).ConfigureAwait(false);

            context.Send(new RevitUiBenchmarkCompletion { ExitCode = exitCode }.Serialize());
        }
    }

    // Repeats the Main method of the generated benchmark program with a host that sends its output to the host process.
    private static int RunBenchmark(RevitUiContext context, RevitUiBenchmarkExecution execution)
    {
        using var host = new RevitUiHost(context);
        var standardOutput = Console.Out;
        var standardError = Console.Error;
        Console.SetOut(host.StandardOutput);
        Console.SetError(host.StandardOutput);

        host.SendSignal(HostSignal.BeforeAnythingElse);
        try
        {
            var runnableTypeName = string.Format(CultureInfo.InvariantCulture, RunnableTypeName, execution.BenchmarkId);
            var runnableType = LoadAssembly(execution.AssemblyPath).GetType(runnableTypeName, throwOnError: true)!;
            var runMethod = runnableType.GetMethod(RunMethodName, BindingFlags.Public | BindingFlags.Static)!;
            runMethod.Invoke(null, [host, execution.BenchmarkName]);
            return 0;
        }
        catch (Exception exception)
        {
            host.WriteLine();
            host.WriteLine((exception is TargetInvocationException { InnerException: { } innerException } ? innerException : exception).ToString());
            return -1;
        }
        finally
        {
            Console.SetOut(standardOutput);
            Console.SetError(standardError);
            host.SendSignal(HostSignal.AfterAll);
        }
    }

    // The generated assembly shares the load context of the runner, with the benchmark assembly and BenchmarkDotNet.
    private static Assembly LoadAssembly(string assemblyPath)
    {
#if NET
        return AssemblyLoadContext.GetLoadContext(typeof(RevitUiBenchmarkRunner).Assembly)!.LoadFromAssemblyPath(assemblyPath);
#else
        return Assembly.LoadFrom(assemblyPath);
#endif
    }

    private static int GetProcessId()
    {
#if NET
        return Environment.ProcessId;
#else
        using var process = Process.GetCurrentProcess();
        return process.Id;
#endif
    }
}
