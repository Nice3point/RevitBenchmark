using System.Globalization;
using System.Reflection;
using BenchmarkDotNet.Engines;
using Nice3point.Revit.Injector.Ui;
#if NET
using System.Runtime.Loader;
#else
using System.Diagnostics;
#endif

namespace Nice3point.BenchmarkDotNet.Revit.Ui;

/// <summary>
///     Represents the entry point that runs the benchmarks of generated benchmark programs inside the Revit user interface application.
/// </summary>
/// <remarks>
///     The runner reports the Revit process to the host process, then runs one benchmark per <see cref="RevitUiMessage.Run" /> message until the host process closes the connection.
///     A benchmark runs synchronously on the Revit thread, inside one Revit API context, the way the generated program runs it in a benchmark process.
///     The console output of the benchmark goes to the host process.
/// </remarks>
[UsedImplicitly]
internal sealed class RevitUiBenchmarkRunner : IRevitUiEntryPoint
{
    private const string RunnableTypeNamePrefix = "BenchmarkDotNet.Autogenerated.Runnable_";
    private const string RunMethodName = "Run";

    /// <summary>
    ///     Gets the context of the Revit user interface application.
    /// </summary>
    /// <value>Defaults to <see langword="null" /> outside the Revit user interface application.</value>
    public static RevitUiContext? Context { get; private set; }

    /// <inheritdoc />
    public async Task RunAsync(RevitUiContext context)
    {
        Context = context;
        context.Send(new RevitUiMessage(RevitUiMessage.Ready, GetProcessId().ToString(CultureInfo.InvariantCulture)).Format());

        while (await context.ReceiveAsync().ConfigureAwait(false) is { } message)
        {
            var runMessage = RevitUiMessage.Parse(message);
            if (runMessage.Kind != RevitUiMessage.Run)
            {
                continue;
            }

            var command = RevitUiRunCommand.Parse(runMessage.Payload);
            var exitCode = -1;
            await context.InvokeAsync(() =>
            {
                exitCode = RunBenchmark(context, command);
                return default;
            }).ConfigureAwait(false);

            context.Send(new RevitUiMessage(RevitUiMessage.Completed, exitCode.ToString(CultureInfo.InvariantCulture)).Format());
        }
    }

    // Repeats the Main method of the generated benchmark program with a host that talks to the host process.
    private static int RunBenchmark(RevitUiContext context, RevitUiRunCommand command)
    {
        using var host = new RevitUiHost(context);
        var standardOutput = Console.Out;
        var standardError = Console.Error;
        Console.SetOut(host.Output);
        Console.SetError(host.Output);

        host.SendSignal(HostSignal.BeforeAnythingElse);
        try
        {
            var runnableType = LoadAssembly(command.AssemblyPath).GetType($"{RunnableTypeNamePrefix}{command.BenchmarkId.ToString(CultureInfo.InvariantCulture)}", throwOnError: true)!;
            var runMethod = runnableType.GetMethod(RunMethodName, BindingFlags.Public | BindingFlags.Static)!;
            runMethod.Invoke(null, [host, command.BenchmarkName]);
            return 0;
        }
        catch (Exception exception)
        {
            host.WriteLine();
            host.WriteLine((exception is TargetInvocationException { InnerException: { } innerException } ? innerException : exception).ToString());
            return -1;
        }
        finally
        {
            Console.SetOut(standardOutput);
            Console.SetError(standardError);
            host.SendSignal(HostSignal.AfterAll);
        }
    }

    // The generated assembly shares the load context of the runner, and with it the benchmark assembly and BenchmarkDotNet.
    private static Assembly LoadAssembly(string assemblyPath)
    {
#if NET
        return AssemblyLoadContext.GetLoadContext(typeof(RevitUiBenchmarkRunner).Assembly)!.LoadFromAssemblyPath(assemblyPath);
#else
        return Assembly.LoadFrom(assemblyPath);
#endif
    }

    private static int GetProcessId()
    {
#if NET
        return Environment.ProcessId;
#else
        using var process = Process.GetCurrentProcess();
        return process.Id;
#endif
    }
}
